`timescale 1ns/1ns
//==============================================================================
// 文件: neuron_cluster_testdata.v
// 说明: 神经元集群测试数据（与 COREPROCESS 中 device_a..device_z 一一对应）
// 用法: 可单独仿真，或将 initial 块中的赋值迁入 tb_coreprocess
//
// 编码约定 (每个 device 低 8bit 作为事件载荷，供 st_8_2ske_latch 捕获):
//   [7:6] 通道/模态类别
//   [5:4] 优先级 (0=低 .. 3=高)
//   [3:0] 事件编号 / 特征码
//==============================================================================

module neuron_cluster_testdata;

    //--------------------------------------------------------------------------
    // 26 个神经元状态寄存器 (与 tb_coreprocess 命名对齐)
    //--------------------------------------------------------------------------
    reg [31:0] device_a, device_b, device_c, device_d, device_e, device_f;
    reg [31:0] device_g, device_h, device_i, device_j, device_k, device_l;
    reg [31:0] device_m, device_n, device_o, device_p, device_q, device_r;
    reg [31:0] device_s, device_t, device_u, device_v, device_w, device_x;
    reg [31:0] device_y, device_z;

    // 集群握手辅助 (与现有 event_z / event_h* 测试风格一致)
    reg en_z, en_h0, en_h1, ack;

    //--------------------------------------------------------------------------
    // 测试向量: 一次「感知 -> 关联 -> 决策 -> 效应」集群发放序列
    //--------------------------------------------------------------------------
    initial begin
        // ---- 清零集群 ----
        device_a = 0; device_b = 0; device_c = 0; device_d = 0; device_e = 0;
        device_f = 0; device_g = 0; device_h = 0; device_i = 0; device_j = 0;
        device_k = 0; device_l = 0; device_m = 0; device_n = 0; device_o = 0;
        device_p = 0; device_q = 0; device_r = 0; device_s = 0; device_t = 0;
        device_u = 0; device_v = 0; device_w = 0; device_x = 0; device_y = 0;
        device_z = 0;
        en_z = 0; en_h0 = 0; en_h1 = 0; ack = 0;

        $dumpfile("neuron_cluster.vcd");
        $dumpvars(0, neuron_cluster_testdata);

        #10;

        //======================================================================
        // 逐个神经元作用说明 + 对应测试数据
        //======================================================================

        //----------------------------------------------------------------------
        // device_a — 视觉传入神经元 (Visual Afferent)
        // 作用: 承接摄像头帧/边缘特征事件，把像素级变化压缩成稀疏发放。
        // 在集群中: 感觉层入口之一，向上游特征细胞 f/g 投射。
        //----------------------------------------------------------------------
        device_a = 32'h0000_0041;   // 模态=视觉(01), 优先级=0, 事件=0x1
        #5;

        //----------------------------------------------------------------------
        // device_b — 听觉传入神经元 (Auditory Afferent)
        // 作用: 承接麦克风能量/音素事件，对突发声响给出短脉冲。
        // 在集群中: 与 a 并行，供多模态绑定细胞 r/s 对齐。
        //----------------------------------------------------------------------
        device_b = 32'h0000_0082;   // 模态=听觉(10), 优先级=0, 事件=0x2
        #5;

        //----------------------------------------------------------------------
        // device_c — 文本/按键传入神经元 (Key/Text Afferent)
        // 作用: 承接键盘符号或命令码，表示离散符号事件而非连续波形。
        // 在集群中: 语义线索源，常与决策层 t/u 直接相关。
        //----------------------------------------------------------------------
        device_c = 32'h0000_00C3;   // 模态=符号(11), 优先级=0, 事件=0x3
        #5;

        //----------------------------------------------------------------------
        // device_d — 指针/空间传入神经元 (Pointer Afferent)
        // 作用: 承接鼠标/触控坐标差分，编码「指向何处」的空间注意。
        // 在集群中: 为注意偏向提供位置偏置，可抑制无关通道 i/j。
        //----------------------------------------------------------------------
        device_d = 32'h0000_0054;   // 模态=视觉空间, 优先级=1, 事件=0x4
        #5;

        //----------------------------------------------------------------------
        // device_e — 网络包传入神经元 (Network Afferent)
        // 作用: 承接网线/远程事件，把外部异步报文映射成本地发放。
        // 在集群中: 外世界接口，优先级通常高于本地传感，避免饿死远程握手。
        //----------------------------------------------------------------------
        device_e = 32'h0000_00D5;   // 模态=网络, 优先级=1, 事件=0x5
        #5;

        //----------------------------------------------------------------------
        // device_f — 初级特征神经元 A (Early Feature A)
        // 作用: 对 a/d 视觉流做第一级特征抽取 (如边、运动方向粗分类)。
        // 在集群中: 感觉层 -> 隐藏层的第一跳，输出稀疏特征码。
        //----------------------------------------------------------------------
        device_f = 32'h0000_0016;   // 特征码 0x16
        #5;

        //----------------------------------------------------------------------
        // device_g — 初级特征神经元 B (Early Feature B)
        // 作用: 对 b/c 听/符号流做互补特征抽取，与 f 形成双通道特征对。
        // 在集群中: 与 f 一起喂入关联核 n..q，实现跨模态对齐前处理。
        //----------------------------------------------------------------------
        device_g = 32'h0000_0027;   // 特征码 0x27
        #5;

        //----------------------------------------------------------------------
        // device_h — 枢纽/仲裁神经元 (Hub / Dual-Port Neuron)  ★重点
        // 作用: 集群总线枢纽；同一载荷可经 h0/h1 两路事件寄存器竞争发放
        //       (对应 tb 中 event_h0 / event_h1)，模拟互斥访问或双读口。
        // 在集群中: 关联层入口闸门，决定哪条路径先获得 grant。
        //----------------------------------------------------------------------
        device_h = 32'h0000_0002;   // 与现有 tb 激励一致: 载荷 0x02
        en_h0 = 1'b1;               // 第一路请求
        #5;
        en_h0 = 1'b0;
        #5;
        en_h1 = 1'b1;               // 第二路请求 (同 data，不同 grant)
        #5;
        en_h1 = 1'b0;
        #5;

        //----------------------------------------------------------------------
        // device_i — 侧抑制神经元 (Lateral Inhibition)
        // 作用: 压低竞争失败者的发放，突出赢家 (WTA 前级)。
        // 在集群中: 接到 h 与 j，防止多源同时占满异步握手通道。
        //----------------------------------------------------------------------
        device_i = 32'h0000_0031;
        #5;

        //----------------------------------------------------------------------
        // device_j — 竞争/互斥神经元 (Competition / Mutex Proxy)
        // 作用: 实现 A/B 请求互斥，对应无时钟互斥元 (st_mutex) 的行为角色。
        // 在集群中: 与 i 配对，保证同一时刻仅一路有效 grant。
        //----------------------------------------------------------------------
        device_j = 32'h0000_0032;
        #5;

        //----------------------------------------------------------------------
        // device_k — 增益/阈值调节神经元 (Gain / Threshold)
        // 作用: 动态抬高或压低集群敏感度，避免噪声引发虚假握手。
        // 在集群中: 偏置 f/g 与 t/u 的有效阈值 (测试数据用低 4bit 表示档位)。
        //----------------------------------------------------------------------
        device_k = 32'h0000_000A;   // 阈值档位 = 10
        #5;

        //----------------------------------------------------------------------
        // device_l — 短时延时链神经元 (Short Delay Line)
        // 作用: 用延时线对齐异步到达的事件，补偿路径偏斜。
        // 在集群中: 绑定前的时间缓冲，对应 st_delay_line 角色。
        //----------------------------------------------------------------------
        device_l = 32'h0000_0048;
        #5;

        //----------------------------------------------------------------------
        // device_m — 时序绑定神经元 (Temporal Binding)
        // 作用: 在时间窗内把多路脉冲标为「同一事件包」。
        // 在集群中: l 之后，把 a..e 多模态输入打成同一 bundle 标签。
        //----------------------------------------------------------------------
        device_m = 32'h0000_0049;
        #5;

        //----------------------------------------------------------------------
        // device_n — 关联存储神经元 0 (Association Cell 0)
        // 作用: 关联核第 0 单元，记忆「视觉特征 <-> 符号」配对。
        // 在集群中: 隐藏关联层，可被 h 闸门选通后写入/读出。
        //----------------------------------------------------------------------
        device_n = 32'h0000_00A0;
        #5;

        //----------------------------------------------------------------------
        // device_o — 关联存储神经元 1 (Association Cell 1)
        // 作用: 关联核第 1 单元，记忆「听觉特征 <-> 动作」配对。
        //----------------------------------------------------------------------
        device_o = 32'h0000_00A1;
        #5;

        //----------------------------------------------------------------------
        // device_p — 关联存储神经元 2 (Association Cell 2)
        // 作用: 关联核第 2 单元，记忆「空间指向 <-> 目标物体」配对。
        //----------------------------------------------------------------------
        device_p = 32'h0000_00A2;
        #5;

        //----------------------------------------------------------------------
        // device_q — 关联存储神经元 3 (Association Cell 3)
        // 作用: 关联核第 3 单元，记忆「网络意图 <-> 本地响应」配对。
        //----------------------------------------------------------------------
        device_q = 32'h0000_00A3;
        #5;

        //----------------------------------------------------------------------
        // device_r — 关系/匹配神经元 (Relation Matcher)
        // 作用: 比较两路事件是否满足预定关系 (对应 st_relation 角色)。
        // 在集群中: 对 n..q 读出结果做一致性检查，通过才允许决策层点火。
        //----------------------------------------------------------------------
        device_r = 32'h0000_00B1;
        #5;

        //----------------------------------------------------------------------
        // device_s — 关系辅神经元 (Relation Auxiliary)
        // 作用: 为 r 提供第二操作数或掩码，构成关系对 (opA, opB)。
        // 在集群中: 与 r 成对出现，测试「匹配成功 / 失败」两种路径。
        //----------------------------------------------------------------------
        device_s = 32'h0000_00B2;
        #5;

        //----------------------------------------------------------------------
        // device_t — 决策神经元 A (Decision A)
        // 作用: 根据关联匹配结果给出主决策码 (走 / 停 / 查询)。
        // 在集群中: 运动前最后一级，输出驱动 v/w/x/y。
        //----------------------------------------------------------------------
        device_t = 32'h0000_00C1;
        #5;

        //----------------------------------------------------------------------
        // device_u — 决策神经元 B / 否决 (Decision B / Veto)
        // 作用: 安全否决或备选策略；当 t 与约束冲突时抑制效应层。
        // 在集群中: 与 t 形成双轨决策，避免单点误发放。
        //----------------------------------------------------------------------
        device_u = 32'h0000_00C0;   // 0 = 不否决
        #5;

        //----------------------------------------------------------------------
        // device_v — 显示效应神经元 (Display Efferent)
        // 作用: 驱动 GUI/HDMI 相关意图 (帧更新、光标高亮等)。
        // 在集群中: 输出层，对应视觉通路的下行。
        //----------------------------------------------------------------------
        device_v = 32'h0000_00E1;
        #5;

        //----------------------------------------------------------------------
        // device_w — 音频效应神经元 (Audio Efferent)
        // 作用: 驱动发声/提示音事件。
        //----------------------------------------------------------------------
        device_w = 32'h0000_00E2;
        #5;

        //----------------------------------------------------------------------
        // device_x — 执行/命令效应神经元 (Actuator Efferent)
        // 作用: 发出离散命令码给下游执行单元 (点击、确认、模式切换)。
        //----------------------------------------------------------------------
        device_x = 32'h0000_00E3;
        #5;

        //----------------------------------------------------------------------
        // device_y — 网络回传效应神经元 (Network Efferent)
        // 作用: 把本地决策封装成对外异步应答事件。
        //----------------------------------------------------------------------
        device_y = 32'h0000_00E4;
        #5;

        //----------------------------------------------------------------------
        // device_z — 全局种子/令牌神经元 (Global Seed / Token)  ★重点
        // 作用: 向集群注入初始事件令牌，启动一轮无时钟握手流水；
        //       对应 tb 中 event_z，是仿真里最常观察的「点火」源。
        // 在集群中: 不绑定具体模态，而是全局相位/回合的起始标记。
        //----------------------------------------------------------------------
        device_z = 32'h0000_0001;   // 首轮令牌
        en_z = 1'b1;
        #5;
        device_z = 32'h0000_0003;   // 令牌更新 (与现有 tb 序列一致)
        #5;
        en_z = 1'b0;
        #10;

        // ---- 完成一轮: 应答拉高，释放事件寄存器 ----
        ack = 1'b1;
        #10;
        ack = 1'b0;
        #20;

        $display("[neuron_cluster] stimulus done.");
        $finish;
    end

endmodule
